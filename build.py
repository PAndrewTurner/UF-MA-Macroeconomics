#!/usr/bin/env python3
"""Bundle content/*.md into assets/content.js.

The app reads window.CONTENT first, so after running this script index.html
works when opened directly from Finder (file://). When the folder is served
over HTTP (python3 -m http.server), the app can also fetch the .md files.

Usage:
    python3 build.py           # rebuild assets/content.js
    python3 build.py --check   # exit 1 if content.js is out of date
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DOCS = {
    "guide": "study-guide.md",
    "formulas": "formula-sheet.md",
    "problems": "problem-sets.md",
    "practice": "practice-questions.md",
}
OUT = ROOT / "assets" / "content.js"


def render() -> str:
    bundle = {key: (ROOT / "content" / name).read_text(encoding="utf-8") for key, name in DOCS.items()}
    body = json.dumps(bundle, ensure_ascii=False, indent=1)
    return (
        "/* Generated by build.py from content/*.md. Do not edit by hand. */\n"
        f"window.CONTENT = {body};\n"
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("assets/content.js is out of date; run python3 build.py")
            return 1
        print("assets/content.js is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
